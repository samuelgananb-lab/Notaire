-- Esquema canonico de Notaire para Supabase.
-- El servidor activo usa exclusivamente las tablas public.usuarios,
-- public.roles, public.metas, public.aportes_meta y public.transacciones.
-- Ejecutar en Supabase SQL Editor solo si alguna tabla aun no existe.

-- En public.usuarios debe existir también auth_id uuid unique para vincular
-- usuarios existentes o nuevos con auth.users.

create table if not exists public.metas (
    id bigint generated by default as identity primary key,
    usuario_id uuid not null references public.usuarios(id) on delete cascade,
    nombre varchar(150) not null,
    monto_objetivo numeric(12, 2) not null check (monto_objetivo > 0),
    monto_actual numeric(12, 2) not null default 0 check (monto_actual >= 0),
    fecha_limite date,
    icono text
);

create table if not exists public.aportes_meta (
    id bigint generated by default as identity primary key,
    meta_id bigint not null references public.metas(id) on delete cascade,
    usuario_id uuid not null references public.usuarios(id) on delete cascade,
    monto numeric(12, 2) not null check (monto > 0),
    fecha timestamptz not null default now()
);

create table if not exists public.transacciones (
    id bigint generated by default as identity primary key,
    usuario_id uuid not null references public.usuarios(id) on delete cascade,
    tipo varchar(20) not null check (tipo in ('ingreso', 'gasto')),
    monto numeric(12, 2) not null check (monto > 0),
    categoria varchar(100) not null,
    descripcion text,
    fecha date not null default current_date
);

create index if not exists idx_metas_usuario on public.metas(usuario_id);
create index if not exists idx_aportes_meta_usuario on public.aportes_meta(usuario_id);
create index if not exists idx_aportes_meta_meta on public.aportes_meta(meta_id);
create index if not exists idx_transacciones_usuario_fecha
    on public.transacciones(usuario_id, fecha desc);
