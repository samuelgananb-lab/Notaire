-- Modulo de tramites notariales para Supabase.
-- Ejecutar una vez en el SQL Editor de Supabase.

create table if not exists public.tramites_notariales (
    id bigint generated by default as identity primary key,
    usuario_id uuid references public.usuarios(id) on delete set null,
    responsable_id uuid references public.usuarios(id) on delete set null,
    tipo varchar(80) not null,
    titulo varchar(180) not null,
    estado varchar(30) not null default 'recibido'
        check (estado in ('recibido', 'en_revision', 'pendiente', 'aprobado', 'finalizado', 'rechazado')),
    fecha_limite date,
    descripcion text,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create index if not exists idx_tramites_estado on public.tramites_notariales(estado);
create index if not exists idx_tramites_usuario on public.tramites_notariales(usuario_id);
create index if not exists idx_tramites_responsable on public.tramites_notariales(responsable_id);
create index if not exists idx_tramites_fecha_limite on public.tramites_notariales(fecha_limite);

alter table public.tramites_notariales enable row level security;

drop policy if exists tramites_admin_policy on public.tramites_notariales;
create policy tramites_admin_policy on public.tramites_notariales
    for all to authenticated
    using (true)
    with check (true);
