-- Auditoria de acciones administrativas para Supabase.
-- Ejecutar una vez en el SQL Editor de Supabase.

create table if not exists public.auditoria_acciones (
    id bigint generated by default as identity primary key,
    actor_id uuid references public.usuarios(id) on delete set null,
    accion varchar(80) not null,
    recurso varchar(80) not null,
    recurso_id text,
    detalles jsonb not null default '{}'::jsonb,
    ip_address inet,
    user_agent text,
    created_at timestamptz not null default now()
);

create index if not exists idx_auditoria_created_at on public.auditoria_acciones(created_at desc);
create index if not exists idx_auditoria_actor on public.auditoria_acciones(actor_id);
create index if not exists idx_auditoria_accion on public.auditoria_acciones(accion);
create index if not exists idx_auditoria_recurso on public.auditoria_acciones(recurso);

alter table public.auditoria_acciones enable row level security;

drop policy if exists auditoria_admin_read_policy on public.auditoria_acciones;
create policy auditoria_admin_read_policy on public.auditoria_acciones
    for select to authenticated
    using (exists (
        select 1 from public.usuarios u
        join public.roles r on r.id_rol = u.id_rol
        where u.id = auth.uid() and lower(r.nombre_rol) = 'admin'
    ));
