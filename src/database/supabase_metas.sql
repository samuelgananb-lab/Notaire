-- Esquema real usado por el proyecto en Supabase.
-- Estas tablas ya existen en el proyecto remoto; este archivo sirve como referencia.

create table if not exists public.metas (
    id bigint generated by default as identity primary key,
    usuario_id uuid not null references public.usuarios(id) on delete cascade,
    nombre varchar(150) not null,
    monto_objetivo numeric(12, 2) not null check (monto_objetivo > 0),
    monto_actual numeric(12, 2) not null default 0 check (monto_actual >= 0),
    fecha_limite date,
    icono text
);

create table if not exists public.aportes_meta (
    id bigint generated by default as identity primary key,
    meta_id bigint not null references public.metas(id) on delete cascade,
    usuario_id uuid not null references public.usuarios(id) on delete cascade,
    monto numeric(12, 2) not null check (monto > 0),
    fecha timestamptz not null default now()
);

create index if not exists idx_metas_usuario
    on public.metas(usuario_id);

create index if not exists idx_aportes_meta_usuario
    on public.aportes_meta(usuario_id);

create index if not exists idx_aportes_meta_meta
    on public.aportes_meta(meta_id);
