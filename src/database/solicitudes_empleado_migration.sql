-- Solicitudes y reportes enviados por clientes y empleados.
-- Los clientes y empleados las crean; el admin responde todas y el empleado las de clientes.
-- Ejecutar una vez en el SQL Editor de Supabase (tambien actualiza la version anterior de la tabla).

create table if not exists public.solicitudes_empleado (
    id bigint generated by default as identity primary key,
    usuario_id uuid not null references public.usuarios(id) on delete cascade,
    rol_origen varchar(20) not null default 'empleado' check (rol_origen in ('cliente', 'empleado')),
    tipo varchar(30) not null
        check (tipo in ('reporte_error', 'solicitud_permiso', 'solicitud_soporte', 'otro')),
    asunto varchar(180) not null,
    descripcion text not null,
    prioridad varchar(10) not null default 'media'
        check (prioridad in ('baja', 'media', 'alta')),
    tramite_id bigint references public.tramites_notariales(id) on delete set null,
    estado varchar(20) not null default 'abierta'
        check (estado in ('abierta', 'en_proceso', 'resuelta', 'rechazada')),
    respuesta text,
    respondido_por uuid references public.usuarios(id) on delete set null,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

do $$
begin
    if exists (select 1 from information_schema.columns
               where table_schema = 'public' and table_name = 'solicitudes_empleado' and column_name = 'empleado_id') then
        alter table public.solicitudes_empleado rename column empleado_id to usuario_id;
    end if;
    if not exists (select 1 from information_schema.columns
                   where table_schema = 'public' and table_name = 'solicitudes_empleado' and column_name = 'rol_origen') then
        alter table public.solicitudes_empleado
            add column rol_origen varchar(20) not null default 'empleado' check (rol_origen in ('cliente', 'empleado'));
    end if;
end $$;

drop index if exists idx_solicitudes_empleado;
create index if not exists idx_solicitudes_usuario on public.solicitudes_empleado(usuario_id);
create index if not exists idx_solicitudes_estado on public.solicitudes_empleado(estado);

alter table public.solicitudes_empleado enable row level security;

drop policy if exists solicitudes_admin_policy on public.solicitudes_empleado;
create policy solicitudes_admin_policy on public.solicitudes_empleado
    for all to authenticated
    using (true)
    with check (true);
